def find_frontends(root: Path) -> list[Path]:
    excludes = load_excludes(root)
    found = []
    for dirpath, dirnames, filenames in os.walk(root):
        d = Path(dirpath)
        relp = d.relative_to(root).as_posix()
        if relp != "." and is_excluded(relp, excludes):
            dirnames[:] = []
            continue
        dirnames[:] = sorted(x for x in dirnames if x not in FRONT_SKIP and not x.startswith("."))
        if "package.json" in filenames:
            try:
                pkg = json.loads(read(d / "package.json"))
            except Exception:
                continue
            deps = {**pkg.get("dependencies", {}), **pkg.get("devDependencies", {})}
            if any(k in deps for k in ("react", "next", "@angular/core", "vue", "vite", "react-scripts")):
                if not any(str(d).startswith(str(f) + os.sep) for f in found):  # nested app = part of the parent
                    found.append(d)
    return sorted(found)


def _norm_url(u: str) -> str:
    u = re.sub(r"\$\{[^}]*\}", "{}", u.strip())
    u = re.sub(r"^\{\}(?=/)", "", u)            # ${base}/api/x -> /api/x
    u = re.sub(r"^https?://[^/]+", "", u)
    return u.split("?")[0] or "/"


def _route_from_app_dir(parts: list[str]) -> str:
    segs = []
    for p_ in parts:
        if p_.startswith("(") and p_.endswith(")"):
            continue  # route group
        if p_.startswith("@"):
            continue  # parallel route slot
        m = re.match(r"^\[\[?\.\.\.(\w+)\]?\]$", p_)
        if m:
            segs.append(f"*{m.group(1)}"); continue
        m = re.match(r"^\[(\w+)\]$", p_)
        segs.append(f":{m.group(1)}" if m else p_)
    return "/" + "/".join(segs)


def extract_frontend(app: Path, root: Path) -> dict:
    pkg = json.loads(read(app / "package.json"))
    deps = {**pkg.get("dependencies", {}), **pkg.get("devDependencies", {})}
    if "next" in deps:
        framework = "nextjs"
    elif "@angular/core" in deps:
        framework = "angular"
    elif "react" in deps and "vite" in deps:
        framework = "react-vite"
    elif "react-scripts" in deps:
        framework = "react-cra"
    elif "react" in deps:
        framework = "react"
    elif "vue" in deps:
        framework = "vue"
    else:
        framework = "other"
    d: dict = {"unit": app.relative_to(root).as_posix(), "kind": "frontend", "name": pkg.get("name", app.name),
               "framework": framework, "scripts": pkg.get("scripts", {}),
               "dependencies": sorted(f"{k} {v}" for k, v in pkg.get("dependencies", {}).items()),
               "dev_dependencies": sorted(f"{k} {v}" for k, v in pkg.get("devDependencies", {}).items()),
               "routes": [], "api_routes": [], "http_calls": [], "env_keys": defaultdict(set), "env_declared": [],
               "risks": [], "top_dirs": [], "counts": Counter()}
    d["top_dirs"] = sorted(x.name for x in app.iterdir() if x.is_dir() and x.name not in FRONT_SKIP and not x.name.startswith("."))
    for f in sorted(app.glob(".env*")):
        if f.name.endswith((".example", ".sample", ".template")) or f.name == ".env.defaults":
            d["env_declared"] += [m.group(1) for m in re.finditer(r"(?m)^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=", read(f))]
    for dirpath, dirnames, filenames in os.walk(app):
        dd = Path(dirpath)
        dirnames[:] = sorted(x for x in dirnames if x not in FRONT_SKIP and not x.startswith("."))
        for fn in sorted(filenames):
            f = dd / fn
            if not fn.endswith(FRONT_EXT):
                continue
            rp = f.relative_to(app).as_posix()
            code = read(f)
            d["counts"]["source_files"] += 1
            if re.search(r"(^|/)components?/", rp):
                d["counts"]["component_files"] += 1
            # ---- routes
            parts = rp.split("/")
            if framework == "nextjs":
                base_i = 1 if parts[0] in ("app", "pages") else (2 if parts[:1] == ["src"] and len(parts) > 1 and parts[1] in ("app", "pages") else -1)
                if base_i > 0:
                    kind = parts[base_i - 1]
                    inner, leaf = parts[base_i:-1], parts[-1]
                    stem = leaf.rsplit(".", 1)[0]
                    if kind == "app" and stem == "page":
                        d["routes"].append({"route": _route_from_app_dir(inner), "file": rp, "router": "app"})
                    elif kind == "app" and stem == "route":
                        methods = sorted(set(re.findall(r"export\s+(?:async\s+)?(?:function|const)\s+(GET|POST|PUT|PATCH|DELETE|HEAD|OPTIONS)\b", code)))
                        d["api_routes"].append({"route": _route_from_app_dir(inner), "methods": methods, "file": rp})
                    elif kind == "pages" and not stem.startswith("_"):
                        segs = inner + ([] if stem == "index" else [stem])
                        route = _route_from_app_dir(segs)
                        if segs[:1] == ["api"]:
                            d["api_routes"].append({"route": route, "methods": ["(handler)"], "file": rp})
                        else:
                            d["routes"].append({"route": route, "file": rp, "router": "pages"})
            elif framework in ("react-vite", "react-cra", "react", "vue"):
                for m in re.finditer(r"<Route\b[^>]*?\bpath=[{]?[\"'`]([^\"'`]+)[\"'`]", code):
                    d["routes"].append({"route": m.group(1), "file": rp, "router": "jsx"})
                if re.search(r"create(?:Browser|Hash|Memory)Router\(|useRoutes\(|createRouter\(|routes\s*[:=]\s*\[", code):
                    for m in re.finditer(r"\bpath\s*:\s*[\"'`]([^\"'`]*)[\"'`]", code):
                        d["routes"].append({"route": m.group(1) or "/", "file": rp, "router": "config"})
            elif framework == "angular" and re.search(r":\s*Routes\b|RouterModule\.for(?:Root|Child)|provideRouter", code):
                for m in re.finditer(r"\{\s*path\s*:\s*[\"'`]([^\"'`]*)[\"'`]([^}]*)", code):
                    target = re.search(r"(component|loadComponent|loadChildren|redirectTo)\s*:", m.group(2))
                    d["routes"].append({"route": "/" + m.group(1), "file": rp, "router": target.group(1) if target else ""})
            # ---- HTTP calls
            for rx in HTTP_CALL_RES:
                for m in rx.finditer(code):
                    d["http_calls"].append({"method": m.group(1).upper(), "url": _norm_url(m.group(3)), "file": rp})
            for m in FETCH_RE.finditer(code):
                url = m.group(2)
                if url.startswith(("/", "http", "${")):
                    d["http_calls"].append({"method": (m.group(3) or "GET").upper(), "url": _norm_url(url), "file": rp})
            # ---- env
            for rx, src in ENV_RES:
                for k in rx.findall(code):
                    d["env_keys"][k].add(rp)
            if framework == "angular" and re.search(r"(^|/)environments?/environment[\w.]*\.ts$", rp):
                body = re.search(r"environment\s*=\s*\{(.*)\}", code, re.S)
                if body:
                    buf = re.sub(r"([`'\"])(?:\\.|(?!\1).)*\1", "''", body.group(1))  # drop string literals (URLs contain ':')
                    depth, keys = 0, []
                    for m in re.finditer(r"([{}])|\b([A-Za-z_]\w*)\s*:", buf):
                        if m.group(1) == "{":
                            depth += 1
                        elif m.group(1) == "}":
                            depth -= 1
                        elif depth == 0:
                            keys.append(m.group(2))
                    for k in keys:
                        d["env_keys"][f"environment.{k}"].add(rp)
            # ---- risks (locations only, never values)
            for m in re.finditer(r"dangerouslySetInnerHTML|bypassSecurityTrust\w+|\[innerHTML\]|v-html", code):
                d["risks"].append({"kind": "raw HTML injection point", "file": rp, "line": code.count("\n", 0, m.start()) + 1})
            for m in re.finditer(r"\beval\(|new Function\(", code):
                d["risks"].append({"kind": "eval / new Function", "file": rp, "line": code.count("\n", 0, m.start()) + 1})
            for m in FRONT_SECRET.finditer(code):
                d["risks"].append({"kind": "hard-coded credential", "file": rp, "line": code.count("\n", 0, m.start()) + 1})
            if framework == "nextjs" and re.search(r"['\"]use client['\"]", code):
                for k in re.findall(r"process\.env\.([A-Z0-9_]+)", code):
                    if not k.startswith("NEXT_PUBLIC_"):
                        d["risks"].append({"kind": f"server-only env {k} read in a client component (undefined in the browser)", "file": rp, "line": 0})
    for k in d["env_keys"]:
        if re.match(r"(NEXT_PUBLIC_|VITE_|REACT_APP_).*(SECRET|PASSWORD|PRIVATE|TOKEN)", k):
            d["risks"].append({"kind": f"env {k} is bundled into the browser but its name suggests a secret", "file": ", ".join(sorted(d["env_keys"][k])), "line": 0})
    # dedupe + sort
    for key in ("routes", "api_routes", "http_calls", "risks"):
        uniq = {json.dumps(x, sort_keys=True) for x in d[key]}
        d[key] = sorted((json.loads(x) for x in uniq), key=lambda x: json.dumps(x, sort_keys=True))
    d["env_keys"] = {k: sorted(v) for k, v in sorted(d["env_keys"].items())}
    d["env_declared"] = sorted(set(d["env_declared"]))
    d["counts"] = dict(sorted(d["counts"].items()))
    return d


def render_frontend(d: dict) -> dict[str, str]:
    files = {}
    n = d["unit"]
    o = [GENERATED_HEADER, f"# {n}: generated overview\n",
         f"**Framework:** {d['framework']}  ·  **package:** `{d['name']}`  ·  "
         f"{d['counts'].get('source_files', 0)} source files ({d['counts'].get('component_files', 0)} in components/)\n",
         "\n## Scripts\n", md_table(["Script", "Command"], [[k, v] for k, v in sorted(d["scripts"].items())]),
         "\n## Dependencies\n", md_table(["Package", "Kind"], [[x, "runtime"] for x in d["dependencies"]] + [[x, "dev"] for x in d["dev_dependencies"]]),
         "\n## Top-level folders\n", ", ".join(f"`{x}`" for x in d["top_dirs"]) + "\n"]
    files["overview.md"] = "".join(o)
    e = [GENERATED_HEADER, f"# {n}: entry points\n", f"\n## Pages / routes ({len(d['routes'])})\n",
         md_table(["Route", "Defined in", "Kind"], [[r["route"], r["file"], r["router"]] for r in d["routes"]])]
    if d["api_routes"]:
        e += [f"\n## API routes served by this app ({len(d['api_routes'])})\n",
              md_table(["Route", "Methods", "File"], [[r["route"], ", ".join(r["methods"]), r["file"]] for r in d["api_routes"]])]
    files["entry-points.md"] = "".join(e)
    c = [GENERATED_HEADER, f"# {n}: configuration\n", "Key **names** only. Values are never extracted.\n",
         "\n## Environment / config keys read by code\n",
         md_table(["Key", "Read in", "Declared in .env.example"], [[k, ", ".join(v), "yes" if k in d["env_declared"] or k.startswith("environment.") else "**no**"] for k, v in d["env_keys"].items()])]
    files["config.md"] = "".join(c)
    r = [GENERATED_HEADER, f"# {n}: backend calls and risks\n", f"\n## HTTP calls made by this app ({len(d['http_calls'])})\n",
         "Matched to backend routes in `.ai/system/generated/contracts.md`.\n\n",
         md_table(["Method", "URL (normalised)", "File"], [[x["method"], x["url"], x["file"]] for x in d["http_calls"]]),
         f"\n## Risks ({len(d['risks'])})\n", md_table(["Risk", "File", "Line"], [[x["kind"], x["file"], x["line"] or ""] for x in d["risks"]])]
    files["contracts-and-risks.md"] = "".join(r)
    return files


def _segments(path: str) -> list[str]:
    return [s_ for s_ in path.strip("/").lower().split("/") if s_]


def _route_matches(call: str, route: str) -> bool:
    a, b = _segments(call), _segments(route)
    if len(a) != len(b):
        return False
    for x, y in zip(a, b):
        if y.startswith(("{", ":")) or x in ("{}",) or x.startswith(":"):
            continue
        if x != y:
            return False
    return True

def db_objects(d: dict) -> list[dict]:
    """Flat list of SQL objects + the connection-string key they run under, for export-db-objects.ps1.
    Deduplicated case-insensitively (SQL Server names are case-insensitive by default)."""
    seen: dict[tuple[str, str], dict] = {}
    for h in d["handlers"]:
        conn = h["connection"][0] if h["connection"] else ""
        for o in h["procs"] + h["tables"]:
            seen.setdefault((o.lower(), conn.lower()), {"object": o, "connection": conn})
    for x in d["legacy_data_access"]:
        for o in x["procs"] + x["tables"]:
            seen.setdefault((o.lower(), "legacy"), {"object": o, "connection": "Constring"})
    return [seen[k] for k in sorted(seen)]


def build(root: Path, only: str | None) -> dict[Path, str]:
    outputs: dict[Path, str] = {}
    sols = find_solutions(root)
    all_data, fronts = [], []
    for sol in sols:
        d = extract_solution(sol)
        d["path"] = sol.relative_to(root).as_posix()
        all_data.append(d)
        if only and only.replace("\\", "/").strip("/").lower() not in (sol.name.lower(), sol.relative_to(root).as_posix().lower()):
            continue
        for fname, content in render_solution(d).items():
            outputs[sol / ".ai" / "generated" / fname] = content
        js = json.loads(json.dumps(d, default=list))
        outputs[sol / ".ai" / "generated" / "catalog.json"] = json.dumps(js, indent=1, sort_keys=True) + "\n"
        outputs[sol / ".ai" / "generated" / "db-objects.json"] = json.dumps(db_objects(d), indent=1) + "\n"
    for app in find_frontends(root):
        f = extract_frontend(app, root)
        fronts.append(f)
        if only and only.replace("\\", "/").strip("/").lower() not in (app.name.lower(), f["unit"].lower()):
            continue
        for fname, content in render_frontend(f).items():
            outputs[app / ".ai" / "generated" / fname] = content
        outputs[app / ".ai" / "generated" / "catalog.json"] = json.dumps(json.loads(json.dumps(f, default=list)), indent=1, sort_keys=True) + "\n"
    if not only:
        for fname, content in render_system(all_data, fronts).items():
            outputs[root / ".ai" / "system" / "generated" / fname] = content
    return outputs


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--root", default=str(Path(__file__).resolve().parents[2]), help="monorepo root")
    ap.add_argument("--solution", help="only this solution: folder name (Gain.Integrations) or repo-relative path (net10_services/Gain.Integrations)")
    ap.add_argument("--check", action="store_true", help="do not write; exit 1 if generated docs are stale")
    a = ap.parse_args()
    root = Path(a.root).resolve()
    outputs = build(root, a.solution)
    if a.solution and not outputs:
        print(f"No solution matches '{a.solution}'. Use the folder name or the path relative to the repo root.", file=sys.stderr)
        return 2
    left = leftovers_in_excluded(root)
    if left:
        print("Note: these generated folders are inside excluded paths (.ai/exclude-paths.txt) and can be deleted:", file=sys.stderr)
        for p in left:
            print(f"  {p.relative_to(root).as_posix()}", file=sys.stderr)
    stale = []
    for path, content in sorted(outputs.items()):
        old = path.read_text(encoding="utf-8") if path.exists() else None
        if old == content:
            continue
        stale.append(path)
        if a.check:
            diff = difflib.unified_diff((old or "").splitlines(), content.splitlines(), str(path), str(path), lineterm="", n=1)
            print("\n".join(list(diff)[:40]))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8", newline="\n")
    if a.check:
        if stale:
            print(f"\n{len(stale)} generated doc file(s) are stale. Run: python tools/claude-kit/docgen.py", file=sys.stderr)
            return 1
        print("Generated docs are up to date.")
        return 0
    print(f"Wrote {len(stale)} file(s); {len(outputs) - len(stale)} unchanged.")
    return 0


if __name__ == "__main__":
    sys.exit(main())

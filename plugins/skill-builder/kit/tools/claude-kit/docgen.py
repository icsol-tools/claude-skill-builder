def render_system(all_data: list[dict], fronts: list[dict] | None = None) -> dict[str, str]:
    fronts = fronts or []
    files = {}
    s = [GENERATED_HEADER, "# Cross-solution contracts (generated)\n",
         "Queue payloads and queues are shared by name between solutions but each solution keeps its **own copy** "
         "of the payload class. A change in one copy is not seen by the others.\n"]
    # queues
    q = defaultdict(lambda: defaultdict(set))
    for d in all_data:
        for u in d["queue_usage"]:
            q[u["queue_key"]][d["solution"]].add(u["role"])
    s.append("\n## Queues by config key\n")
    s.append(md_table(["Queue config key", "Solutions and roles"],
                      [[k, "; ".join(f"{sol}: {', '.join(sorted(r))}" for sol, r in sorted(v.items()))] for k, v in sorted(q.items())]))
    # payloads compared
    s.append("\n## Payload classes by solution\n")
    rows = []
    for d in all_data:
        for p in d["queue_payloads"]:
            rows.append([p["name"], d["solution"], ", ".join(p["props"])])
    s.append(md_table(["Class", "Solution", "Properties"], sorted(rows)))
    # integration message drift
    im = [(d["solution"], p) for d in all_data for p in d["queue_payloads"] if re.match(r"IntegrationMessageQueue(Payload)?$|IntegrationQueuePayload$", p["name"])]
    if len(im) > 1:
        s.append("\n## Drift: integration message payload\n")
        allp = sorted({x.split(":")[0] for _, p in im for x in p["props"]})
        rows = []
        for prop in allp:
            rows.append([prop] + [("yes" if any(x.startswith(prop + ":") for x in p["props"]) else "**missing**") for _, p in im])
        s.append(md_table(["Property"] + [f"{sol}/{p['name']}" for sol, p in im], rows))
    # shared sql objects
    obj = defaultdict(set)
    for d in all_data:
        for h in d["handlers"]:
            for o_ in h["procs"] + h["tables"]:
                obj[o_.lower()].add(d["solution"])
        for x in d["legacy_data_access"]:
            for o_ in x["procs"] + x["tables"]:
                obj[o_.lower()].add(d["solution"])
    shared = {k: v for k, v in obj.items() if len(v) > 1}
    s.append("\n## SQL objects used by more than one solution\n")
    s.append("Changing one of these affects every solution listed.\n")
    s.append(md_table(["SQL object (lower-cased)", "Solutions"], [[k, ", ".join(sorted(v))] for k, v in sorted(shared.items())]))
    files["contracts.md"] = "".join(s)

    i = [GENERATED_HEADER, "# Solution index (generated)\n"]
    rows = []
    for d in all_data:
        rows.append([d["solution"], len(d["projects"]), sum(len(c["actions"]) for c in d["controllers"]),
                     len([c for c in d["controllers"] if c["style"] == "CQS"]), len([c for c in d["controllers"] if c["style"] == "Legacy BA/DA"]),
                     len(d["hosted_services"]), len(d["handlers"]), sum(n for _, n in d["unsafe_sql"])])
    i.append(md_table(["Solution", "Projects", "HTTP actions", "CQS controllers", "Legacy controllers", "Hosted services", "Handlers", "Unsafe SQL fragments"], rows))
    if fronts:
        i.append("\n## Frontend apps\n")
        i.append(md_table(["App", "Framework", "Routes", "API routes", "Backend calls", "Risks"],
                          [[f["unit"], f["framework"], len(f["routes"]), len(f["api_routes"]), len(f["http_calls"]), len(f["risks"])] for f in fronts]))
    files["index.md"] = "".join(i)

    # ---- frontend -> backend calls, matched against every backend route in the repo
    if fronts:
        backend = []
        for d in all_data:
            for c in d["controllers"]:
                for a in c["actions"]:
                    backend.append((a["verb"], a["route"], f"{d.get('path', d['solution'])}: {c['name']}.{a['method']}"))
        for f in fronts:
            for r in f["api_routes"]:
                for m in (r["methods"] or ["(handler)"]):
                    backend.append((m, r["route"], f"{f['unit']}: {r['file']}"))
        rows = []
        for f in fronts:
            for call in f["http_calls"]:
                hits = [b for b in backend if _route_matches(call["url"], b[1]) and (b[0] == call["method"] or b[0] == "(handler)")]
                rows.append([f["unit"], call["method"], call["url"], "; ".join(sorted({h[2] for h in hits})) or "**not found in this repo**"])
        files["contracts.md"] += ("\n## Frontend -> backend calls\n"
            "Each HTTP call a frontend makes, and the backend route in this repo that serves it. "
            "\"not found\" means another repo, an external API, or a broken call.\n\n"
            + md_table(["Frontend", "Method", "URL", "Served by"], sorted(rows)))
    return files



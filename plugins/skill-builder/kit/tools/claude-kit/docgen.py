#!/usr/bin/env python3
"""
docgen (claude-kit): deterministic catalogue extractor for .NET (Core and Framework) solutions and
frontend apps (React/Vite, Next.js, Angular).

Reads C# / csproj / appsettings files (never config VALUES, only key names) and writes
<solution>/.ai/generated/*.md plus catalog.json, and a cross-solution system catalogue
in .ai/system/generated/.

Output is deterministic (sorted, no timestamps) so CI can fail when generated docs are
stale:  python tools/claude-kit/docgen.py --check

Usage:
  python tools/claude-kit/docgen.py                    # all solutions under repo root
  python tools/claude-kit/docgen.py --solution <folder or path>
  python tools/claude-kit/docgen.py --check            # exit 1 if anything is stale
  python tools/claude-kit/docgen.py --root <repo-root>

Requires Python 3.10+ and nothing else. Regex-based: good enough for catalogues, not a
compiler. When a pattern is not recognised the item is simply missing - the narrative
docs and the human review cover the rest.
"""
from __future__ import annotations

import argparse
import difflib
import json
import os
import re
import sys
from collections import Counter, defaultdict
from pathlib import Path

SKIP_DIRS = {"bin", "obj", ".vs", ".git", "node_modules", "packages", "TestResults", ".ai"}
GENERATED_HEADER = (
    "<!-- GENERATED by tools/claude-kit/docgen.py. Do not edit by hand: change the code and run "
    "`python tools/claude-kit/docgen.py`. -->\n"
)

# --------------------------------------------------------------------------- C# lexing


def strip_comments(src: str) -> str:
    """Remove // and /* */ comments, keeping string literals intact."""
    out = []
    i, n = 0, len(src)
    while i < n:
        c = src[i]
        nxt = src[i + 1] if i + 1 < n else ""
        if c == "/" and nxt == "/":
            j = src.find("\n", i)
            i = n if j == -1 else j
            continue
        if c == "/" and nxt == "*":
            j = src.find("*/", i + 2)
            i = n if j == -1 else j + 2
            continue
        if c == '"' or (c in "$@" and nxt in '"$@'):
            j, lit = read_string(src, i)
            out.append(lit)
            i = j
            continue
        if c == "'":
            # char literal
            j = i + 1
            while j < n and src[j] != "'":
                j += 2 if src[j] == "\\" else 1
            out.append(src[i : j + 1])
            i = j + 1
            continue
        out.append(c)
        i += 1
    return "".join(out)


def read_string(src: str, i: int) -> tuple[int, str]:
    """Read a C# string literal starting at i (handles $, @, $@, @$, raw \"\"\")."""
    n = len(src)
    start = i
    verbatim = False
    while i < n and src[i] in "$@":
        if src[i] == "@":
            verbatim = True
        i += 1
    if src.startswith('"""', i):  # raw string literal
        j = src.find('"""', i + 3)
        j = n if j == -1 else j + 3
        return j, src[start:j]
    i += 1  # opening quote
    while i < n:
        c = src[i]
        if verbatim:
            if c == '"':
                if i + 1 < n and src[i + 1] == '"':
                    i += 2
                    continue
                return i + 1, src[start : i + 1]
        else:
            if c == "\\":
                i += 2
                continue
            if c == '"':
                return i + 1, src[start : i + 1]
            if c == "\n":
                return i, src[start:i]
        i += 1
    return n, src[start:n]


STRING_RE = re.compile(r'(\$@|@\$|\$|@)?"(?:[^"\\\n]|\\.)*"|(\$@|@\$|@)"(?:[^"]|"")*"')


def string_literals(code: str) -> list[str]:
    lits = []
    i, n = 0, len(code)
    while i < n:
        c = code[i]
        nxt = code[i + 1] if i + 1 < n else ""
        if c == '"' or (c in "$@" and nxt in '"$@'):
            j, lit = read_string(code, i)
            body = re.sub(r'^[\$@]*"(""")?|("""|")$', "", lit)
            lits.append(body)
            i = max(j, i + 1)
            continue
        i += 1
    return lits


# --------------------------------------------------------------------------- helpers


def rel(p: Path, base: Path) -> str:
    return p.relative_to(base).as_posix()


def walk(base: Path, suffixes: tuple[str, ...]):
    for dirpath, dirnames, filenames in os.walk(base):
        dirnames[:] = sorted(d for d in dirnames if d not in SKIP_DIRS)
        for f in sorted(filenames):
            if f.endswith(suffixes):
                yield Path(dirpath) / f


def read(p: Path) -> str:
    return p.read_text(encoding="utf-8-sig", errors="replace")


def norm_obj(name: str) -> str:
    """Normalise SQL object names: strip brackets, keep db.schema.name casing as written."""
    return re.sub(r"[\[\]]", "", name).strip().rstrip(";,)")


def md_table(headers: list[str], rows: list[list[str]]) -> str:
    if not rows:
        return "_None found._\n"
    esc = lambda s: str(s).replace("|", "\\|").replace("\n", " ")
    out = "| " + " | ".join(headers) + " |\n"
    out += "|" + "|".join("---" for _ in headers) + "|\n"
    for r in rows:
        out += "| " + " | ".join(esc(c) for c in r) + " |\n"
    return out


def load_excludes(root: Path) -> list[str]:
    """Repo-relative folders to ignore, from .ai/exclude-paths.txt (one per line, # comments)."""
    f = root / ".ai" / "exclude-paths.txt"
    if not f.exists():
        return []
    out = []
    for line in f.read_text(encoding="utf-8-sig").splitlines():
        line = line.split("#", 1)[0].strip().replace("\\", "/").strip("/")
        if line:
            out.append(line)
    return out


def is_excluded(rel_path: str, excludes: list[str]) -> bool:
    r = rel_path.replace("\\", "/").strip("/").lower()
    return any(r == e.lower() or r.startswith(e.lower() + "/") for e in excludes)


def find_solutions(root: Path) -> list[Path]:
    excludes = load_excludes(root)
    sols = set()
    for dirpath, dirnames, filenames in os.walk(root):
        relp = Path(dirpath).relative_to(root).as_posix()
        if relp != "." and is_excluded(relp, excludes):
            dirnames[:] = []
            continue
        dirnames[:] = sorted(d for d in dirnames if d not in SKIP_DIRS and not d.startswith("."))
        if any(f.endswith((".sln", ".slnx")) for f in filenames):
            sols.add(Path(dirpath))
            dirnames[:] = []  # a solution folder owns everything below it (nested .sln files are ignored)
    return sorted(sols)


def leftovers_in_excluded(root: Path) -> list[Path]:
    """Generated folders this tool wrote before a path was excluded - safe to delete."""
    found = []
    for e in load_excludes(root):
        base = root / e
        if base.is_dir():
            found += sorted(p for p in base.rglob("generated") if p.parent.name == ".ai")
    return found


# --------------------------------------------------------------------------- extraction

SQL_KEYWORDS = {"select", "set", "where", "values", "as", "on", "with", "nolock", "dbo", "the"}
EXEC_RE = re.compile(r"\bEXEC(?:UTE)?\s+((?:\[?\w+\]?\.){0,2}\[?\w+\]?)", re.I)
THREE_PART_RE = re.compile(r"\b(\[?\w+\]?\.\[?dbo\]?\.\[?\w+\]?)", re.I)
FROM_JOIN_RE = re.compile(r"\b(?:FROM|JOIN|UPDATE|INSERT\s+INTO|DELETE\s+FROM|MERGE\s+INTO?)\s+((?:\[?\w+\]?\.){0,2}\[?\w+\]?)", re.I)
CLASS_RE = re.compile(r"\b(?:public|internal)\s+(?:sealed\s+|static\s+|abstract\s+|partial\s+)*class\s+(\w+)(?:<[^>]+>)?\s*(?::\s*([^{]+))?\{")
QH_RE = re.compile(r"IQueryHandler<\s*(\w+)\s*,\s*([\w<>\[\], ]+?)\s*>\s*(?:,|$|\{|\s)")
CH_RE = re.compile(r"ICommandHandler<\s*(\w+)\s*>")
CTOR_PARAM_TYPES_RE = re.compile(r"\b(\w+(?:<[\w\.]+>)?)\s+\w+\s*[,)]")
CONN_RE = re.compile(r"\.Value\.(\w*Connection\w*)|GetConnectionString\(\s*\"(\w+)\"\s*\)")
HANDLE_RE = re.compile(r"HandleAsync<\s*(\w+)")
CONFIG_KEY_RES = [
    re.compile(r"(?:configuration|Configuration|_configuration|config)\[\s*\"([^\"]+)\"\s*\]"),
    re.compile(r"GetValue<[^>]+>\(\s*\"([^\"]+)\""),
    re.compile(r"GetSection\(\s*\"([^\"]+)\"\s*\)"),
    re.compile(r"AppSettingsDataAccess\.GetValue\(\s*\"([^\"]+)\"\s*\)"),
]
FX_CONFIG_RES = [  # .NET Framework ConfigurationManager
    (re.compile(r"ConfigurationManager\.AppSettings\[\s*\"([^\"]+)\"\s*\]"), "appSettings:"),
    (re.compile(r"ConfigurationManager\.ConnectionStrings\[\s*\"([^\"]+)\"\s*\]"), "ConnectionStrings:"),
]


SQL_START_RE = re.compile(r"^\s*[,;(]?\s*(WITH|SELECT|EXEC|EXECUTE|UPDATE|INSERT|DELETE|MERGE|DECLARE|FROM|JOIN|INNER|LEFT|RIGHT|CROSS|OUTER|WHERE|AND|OR|SET|IF|BEGIN|UNION|ORDER|GROUP)\b", re.I)
CTE_RE = re.compile(r"(?:\bWITH|,)\s*\[?(\w+)\]?\s*(?:\([^)]*\))?\s+AS\s*\(", re.I)


def sql_objects(lits: list[str]) -> tuple[set[str], set[str]]:
    """SQL objects referenced in string literals.
    Three-part names (Db.dbo.Name) are taken from any literal. EXEC/FROM/JOIN targets only from
    literals that look like SQL, so log messages ("... from stored procedure") are ignored.
    CTE names are excluded. One-part names must look like objects (no all-lowercase English words)."""
    procs, tables = set(), set()
    sql_lits = [l for l in lits if SQL_START_RE.match(l) or re.search(r"\bSELECT\b.+\bFROM\b", l, re.I | re.S)]
    ctes = {m.group(1).lower() for l in sql_lits for m in CTE_RE.finditer(l)}

    def keep(name: str) -> bool:
        if name.lower() in SQL_KEYWORDS or name.lower() in ctes or name.startswith(("@", "#")):
            return False
        if "." not in name and (name.islower() or len(name) < 3):
            return False
        return True

    for l in sql_lits:
        for m in EXEC_RE.finditer(l):
            name = norm_obj(m.group(1))
            if keep(name):
                procs.add(name)
        for m in FROM_JOIN_RE.finditer(l):
            name = norm_obj(m.group(1))
            if keep(name):
                tables.add(name)
    for l in lits:
        for m in THREE_PART_RE.finditer(l):
            name = norm_obj(m.group(1))
            if name not in procs:
                tables.add(name)
    tables -= procs
    return procs, tables


def unsafe_sql_count(code: str) -> int:
    """Count SQL text built from values: concatenation after a SQL literal or interpolation with quotes."""
    n = 0
    # "EXEC ... '" + value   /   "... @p = '" + value
    n += len(re.findall(r"\"[^\"\n]*(?:\bEXEC|\bSELECT|\bUPDATE|\bINSERT|\bDELETE|@\w+\s*=)[^\"\n]*\"\s*\+", code, re.I))
    # $"... @p = '{value}'"  or $"... @p = {value}"
    n += len(re.findall(r"\$@?\"[^\"\n]*(?:\bEXEC|\bSELECT|\bUPDATE|\bINSERT|\bDELETE|@\w+\s*=)[^\"\n]*\{[^}]+\}", code, re.I))
    return n


def extract_solution(sol: Path) -> dict:
    data: dict = {
        "solution": sol.name,
        "projects": [],
        "di": defaultdict(list),
        "controllers": [],
        "hosted_services": [],
        "routing": [],
        "handlers": [],
        "contexts": [],
        "legacy_data_access": [],
        "config_keys_used": defaultdict(set),
        "appsettings_keys": {},
        "queue_payloads": [],
        "queue_usage": [],
        "endpoint_constants": [],
        "compile_removed": [],
        "unsafe_sql": [],
        "empty_projects": [],
        "commented_out_files": [],
    }

    # ---- projects
    for proj in walk(sol, (".csproj",)):
        t = read(proj)
        pdir = proj.parent
        cs_count = sum(1 for _ in walk(pdir, (".cs",)))
        tf = re.search(r"<TargetFrameworks?>([^<]+)<", t) or re.search(r"<TargetFrameworkVersion>([^<]+)<", t)
        pkgs = re.findall(r'<PackageReference\s+Include="([^"]+)"\s+Version="([^"]+)"', t)
        if (pdir / "packages.config").exists():
            pkgs += re.findall(r'<package\s+id="([^"]+)"\s+version="([^"]+)"', read(pdir / "packages.config"))
        refs = [Path(r.replace("\\", "/")).stem for r in re.findall(r'<ProjectReference\s+Include="([^"]+)"', t)]
        sdk = re.search(r'<Project\s+Sdk="([^"]+)"', t)
        removed = re.findall(r'<Compile\s+Remove="([^"]+)"', t)
        data["projects"].append({
            "name": proj.stem,
            "path": rel(pdir, sol),
            "sdk": sdk.group(1) if sdk else "legacy msbuild (.NET Framework)",
            "target": tf.group(1) if tf else "",
            "packages": sorted(f"{a} {b}" for a, b in pkgs),
            "references": sorted(refs),
            "cs_files": cs_count,
        })
        for r in removed:
            data["compile_removed"].append(f"{proj.stem}: {r}")
        if cs_count <= 1:
            data["empty_projects"].append(f"{proj.stem} ({cs_count} .cs file)")
    slnx = list(sol.glob("*.slnx")) + list(sol.glob("*.sln"))
    if slnx:
        st = read(slnx[0])
        listed = {Path(p.replace("\\", "/")).stem for p in re.findall(r'(?:Path="|", ")([^"]+\.csproj)', st)}
        for p in data["projects"]:
            p["in_solution_file"] = p["name"] in listed

    # ---- appsettings key names (values are NEVER read into the output)
    for f in walk(sol, (".json",)):
        if not f.name.startswith("appsettings"):
            continue
        try:
            txt = re.sub(r"(?m)^\s*//.*$|(?<=[,{\[\s])//[^\n\"]*$", "", read(f))
            txt = re.sub(r",\s*([}\]])", r"\1", txt)
            j = json.loads(txt)
        except Exception:
            continue
        keys = []

        def flat(o, prefix=""):
            if isinstance(o, dict):
                for k, v in o.items():
                    flat(v, f"{prefix}{k}:" if isinstance(v, dict) else f"{prefix}{k}")
                    if not isinstance(v, dict):
                        keys.append(f"{prefix}{k}")
        flat(j)
        data["appsettings_keys"][rel(f, sol)] = sorted(set(keys))

    # ---- web.config / app.config key NAMES (.NET Framework). Values are never read into the output.
    for f in walk(sol, (".config",)):
        if f.name.lower() not in ("web.config", "app.config") and not re.match(r"(?i)web\.\w+\.config$", f.name):
            continue
        t = read(f)
        keys = [f"appSettings:{k}" for k in re.findall(r'<add\s+key="([^"]+)"', t)]
        keys += [f"ConnectionStrings:{k}" for k in re.findall(r'<add\s+name="([^"]+)"\s+connectionString=', t)]
        if keys:
            data["appsettings_keys"][rel(f, sol)] = sorted(set(keys))

    # ---- C# files
    for f in walk(sol, (".cs",)):
        raw = read(f)
        code = strip_comments(raw)
        rp = rel(f, sol)
        if re.search(r"\bclass\s+\w+", raw) and not re.search(r"\b(class|interface|record|enum|struct)\s+\w+", code):
            data["commented_out_files"].append(rp)
            continue
        lits = string_literals(code)
        classes = CLASS_RE.findall(code)
        cls_names = [c[0] for c in classes]
        bases = " ".join(c[1] for c in classes)

        for rx in CONFIG_KEY_RES:
            for k in rx.findall(code):
                data["config_keys_used"][k].add(rp)
        for rx, prefix in FX_CONFIG_RES:
            for k in rx.findall(code):
                data["config_keys_used"][prefix + k].add(rp)
        for m in CONN_RE.finditer(code):
            k = m.group(1) or m.group(2)
            data["config_keys_used"][f"ConnectionStrings:{k}"].add(rp)

        n_unsafe = unsafe_sql_count(code)
        if n_unsafe:
            data["unsafe_sql"].append((rp, n_unsafe))

        # DI loader
        if re.search(r"\bvoid\s+ConfigureServices\s*\(|AddScoped<|AddHostedService<", code) and ("DILoader" in f.name or "Program" in f.name or "Startup" in f.name):
            for kind, a, b in re.findall(r"\.(AddScoped|AddSingleton|AddTransient)<\s*([\w\.<>]+?)\s*(?:,\s*([\w\.<>]+?)\s*)?>", code):
                data["di"][kind].append(f"{a} -> {b}" if b else a)
            for hs in re.findall(r"AddHostedService<\s*([\w\.]+)\s*>", code):
                data["di"]["AddHostedService"].append(hs)
            for ctx, cs in re.findall(r"AddDbContext<\s*(\w+)\s*>\([^;]*?GetConnectionString\(\s*\"(\w+)\"", code, re.S):
                data["di"]["AddDbContext"].append(f"{ctx} -> {cs}")
            for asm in re.findall(r"AddCommandQueryHandlers\(\s*services\s*,\s*\"([\w\.]+)\"", code):
                data["di"]["Handler assemblies (auto-registered)"].append(asm)
            for v in re.findall(r"AddScoped<\s*IValidator<\s*(\w+)\s*>\s*,\s*(\w+)\s*>", code):
                data["di"]["Validators"].append(f"{v[0]} -> {v[1]}")

        # Controllers
        for cname, cbase in classes:
            if not re.search(r"\b(Controller|ControllerBase|ApiController)\b", cbase or ""):
                continue
            prefix = ""
            m = re.search(r"\[(?:Route|RoutePrefix)\(\s*\"([^\"]*)\"\s*\)\]\s*(?:\[[^\]]+\]\s*)*public\s+class\s+" + cname, code)
            if m:
                prefix = m.group(1)
            if re.search(r"I(Query|Command)Dispatcher", code):
                style = "CQS"
            elif re.search(r"\bnew\s+\w+BA\s*\(|\b\w+BA\s+\w+\s*;|\bDBConnection\b|\.ExecuteSQL\s*\(", code):
                style = "Legacy BA/DA"
            else:
                style = "Other"
            actions = []
            # split on attributes blocks preceding public methods
            for am in re.finditer(r"((?:\[[^\]]*\]\s*)+)public\s+(?:async\s+)?[\w<>\[\],\s]+?\s+(\w+)\s*\(", code):
                attrs, meth = am.group(1), am.group(2)
                verbs = re.findall(r"\[Http(Get|Post|Put|Patch|Delete)(?:\(\s*\"([^\"]*)\"\s*\))?", attrs)
                if not verbs:
                    continue
                route = re.search(r"\[Route\(\s*\"([^\"]*)\"\s*\)\]", attrs)
                verb = verbs[0][0].upper()
                path = verbs[0][1] or (route.group(1) if route else "")
                full = path if path.startswith("api/") or path.startswith("/") else "/".join(x for x in [prefix, path] if x)
                vf = re.search(r"ValidationFilter<\s*(\w+)\s*>", attrs)
                # body to next action
                body_end = code.find("[Http", am.end())
                body = code[am.end(): body_end if body_end != -1 else len(code)]
                dispatched = sorted(set(HANDLE_RE.findall(body)))
                ba_calls = sorted(set(re.findall(r"\b(?:BA|\w+BA)\.(\w+)\(", body)))
                actions.append({
                    "verb": verb, "route": "/" + full.lstrip("/"), "method": meth,
                    "dispatches": dispatched, "legacy_calls": ba_calls,
                    "validation": vf.group(1) if vf else "",
                })
            data["controllers"].append({"name": cname, "file": rp, "style": style, "actions": actions})

        # Hosted services
        for cname, cbase in classes:
            if not re.search(r"\b(IHostedService|BackgroundService)\b", cbase or ""):
                continue
            kind = "Consumer" if "RabbitMQConsumer" in code else ("Scheduler" if re.search(r"\bTimer\b|PeriodicTimer|Task\.Delay", code) else "Hosted service")
            qkeys = sorted(set(re.findall(r"\"(Queues:\w+)\"", code)))
            tkeys = sorted(set(k for k in re.findall(r"\"(\w*(?:Timer|Interval|RunTime)\w*)\"", code)))
            data["hosted_services"].append({"name": cname, "file": rp, "kind": kind, "queue_keys": qkeys, "timer_keys": tkeys,
                                            "dispatches": sorted(set(HANDLE_RE.findall(code)))})

        # Routing switches on codes (consumers, routers)
        for sm in re.finditer(r"switch\s*\(\s*([\w\.\?]+?)(?:\?\.ToLower\(\)|\.ToLower\(\)|\?\.ToUpper\(\)|\.ToUpper\(\))?\s*\)\s*\{", code):
            subject = sm.group(1).split(".")[-1].rstrip("?")
            if not re.search(r"(Process|SubProcess|Code|Type)", subject, re.I):
                continue
            # find matching brace
            depth, j = 1, sm.end()
            while j < len(code) and depth:
                depth += {"{": 1, "}": -1}.get(code[j], 0)
                j += 1
            block = code[sm.end(): j]
            parts = re.split(r"((?:\s*case\s+\"[^\"]+\"\s*:)+)", block)
            for k in range(1, len(parts), 2):
                labels = re.findall(r"case\s+\"([^\"]+)\"", parts[k])
                body = parts[k + 1] if k + 1 < len(parts) else ""
                body = body.split("break;")[0].split("return ")[0] if "break;" in body or "return" in body else body
                call = re.search(r"await\s+([\w\.]+)\s*\(|=\s*await\s+([\w\.]+)\s*\(|\b(Call\w+|Handle\w+|Publish\w+)\s*\(", body)
                target = next((g for g in (call.groups() if call else []) if g), "")
                for lab in labels:
                    data["routing"].append({"file": rp, "switch_on": subject, "code": lab, "target": target})

        # Handlers
        for cname, cbase in classes:
            qh = QH_RE.search((cbase or "") + " ")
            ch = CH_RE.search(cbase or "")
            if not (qh or ch):
                continue
            ctor = re.search(r"public\s+" + cname + r"\s*\(([^)]*)\)", code, re.S)
            ptypes = CTOR_PARAM_TYPES_RE.findall((ctor.group(1) + ")") if ctor else "")
            ctxs = sorted(set(p for p in ptypes if p.endswith("Context") and not p.startswith("IHttp")))
            repos = sorted(set(re.sub(r".*<([\w\.]+)>", r"\1", p) for p in ptypes if p.startswith("IRepository")))
            conns = sorted(set((m.group(1) or m.group(2)) for m in CONN_RE.finditer(code)))
            procs, tables = sql_objects(lits)
            sp_names = []
            if "CommandType.StoredProcedure" in code:
                sp_names = [l for l in lits if re.fullmatch(r"[\[\]\w]+(\.[\[\]\w]+){0,2}", l) and not l.isupper()]
            procs |= {norm_obj(s) for s in sp_names}
            access = []
            if re.search(r"\bQuery\w*Async\b|\bExecute\w*Async\s*\(\s*(?:sql|\")", code) and "Dapper" in code:
                access.append("Dapper")
            if re.search(r"FromSqlRaw|ExecuteSqlRaw|SqlQueryRaw|FromSqlInterpolated|ExecuteSqlInterpolated", code):
                access.append("EF raw SQL")
            if ctxs or repos:
                access.append("EF")
            validator = bool(re.search(r"Validator\s*\(|\.Validate\(", code))
            data["handlers"].append({
                "kind": "Query" if qh else "Command",
                "message": (qh.group(1) if qh else ch.group(1)),
                "result": (qh.group(2).strip() if qh else ""),
                "handler": cname, "file": rp, "connection": conns, "contexts": ctxs, "repositories": repos,
                "procs": sorted(procs), "tables": sorted(tables), "access": access, "validates": validator,
                "dispatches": sorted(set(HANDLE_RE.findall(code)) - {(qh.group(1) if qh else ch.group(1))}),
            })

        # DbContexts
        for cname, cbase in classes:
            if "DbContext" not in (cbase or ""):
                continue
            sets = re.findall(r"DbSet<\s*(\w+)\s*>\s+(\w+)", code)
            tbl = dict(re.findall(r"Entity<\s*(\w+)\s*>\s*\(\s*\w+\s*=>\s*\{[^{}]*?ToTable\(\s*\"([^\"]+)\"", code, re.S))
            keyless = set(re.findall(r"Entity<\s*(\w+)\s*>\s*\(\s*\w+\s*=>\s*\{[^{}]*?HasNoKey\(\)", code, re.S))
            data["contexts"].append({"name": cname, "file": rp,
                                     "sets": sorted(f"{e} -> {tbl.get(e, '(no ToTable)')}{' [keyless]' if e in keyless else ''}" for e, _ in sets)})

        # Legacy data access (BusinessAccess style)
        if re.search(r"\bDBConnection\b|ExecuteSQL\s*\(", code) and not any(re.search(r"I(Query|Command)Handler", c[1] or "") for c in classes):
            procs, tables = sql_objects(lits)
            if procs or tables:
                data["legacy_data_access"].append({"file": rp, "classes": cls_names, "procs": sorted(procs), "tables": sorted(tables)})

        # Queue payload contracts
        for cname, cbase in classes:
            if re.search(r"(QueuePayload|MessageQueue|QueueMessage|QueueDto)\w*$", cname) or "/QueuePayload/" in "/" + rp:
                m = re.search(r"class\s+" + cname + r"\b[^{]*\{", code)
                if not m:
                    continue
                depth, j = 1, m.end()
                while j < len(code) and depth:
                    depth += {"{": 1, "}": -1}.get(code[j], 0)
                    j += 1
                props = re.findall(r"public\s+([\w<>\[\]\?,\. ]+?)\s+(\w+)\s*\{\s*get", code[m.end():j])
                data["queue_payloads"].append({"name": cname, "file": rp, "props": sorted(f"{n}: {t.strip()}" for t, n in props)})

        # Queue usage (publish / consume)
        for qk in re.findall(r"\"Queues:(\w+)\"", code):
            role = "consume" if "RabbitMQConsumer" in code else ("publish" if ".Publish(" in code else "reference")
            data["queue_usage"].append({"queue_key": qk, "role": role, "file": rp})
        for qk in re.findall(r"_queues\.(\w+)", code):
            role = "publish" if ".Publish(" in code else "reference"
            data["queue_usage"].append({"queue_key": qk, "role": role, "file": rp})

        # Endpoint constants
        if re.search(r"Endpoint", f.stem):
            for name, val in re.findall(r"public\s+const\s+string\s+(\w+)\s*=\s*\"([^\"]*)\"", code):
                data["endpoint_constants"].append((name, val, rp))

    # dedupe queue usage
    seen = set()
    qu = []
    for q in data["queue_usage"]:
        key = (q["queue_key"], q["role"], q["file"])
        if key not in seen:
            seen.add(key)
            qu.append(q)
    data["queue_usage"] = sorted(qu, key=lambda q: (q["queue_key"], q["role"], q["file"]))
    # .NET configuration keys are case-insensitive: merge spellings so the catalogue never holds two
    # keys that differ only by case (Windows PowerShell's ConvertFrom-Json rejects that)
    merged: dict[str, set] = {}
    spellings: dict[str, set] = defaultdict(set)
    for k in sorted(data["config_keys_used"]):
        canon = next((c for c in merged if c.lower() == k.lower()), k)
        merged.setdefault(canon, set()).update(data["config_keys_used"][k])
        spellings[canon].add(k)
    data["config_keys_used"] = {k: sorted(v) for k, v in sorted(merged.items())}
    data["config_key_spellings"] = {k: sorted(v) for k, v in sorted(spellings.items()) if len(v) > 1}
    data["di"] = {k: sorted(set(v)) for k, v in sorted(data["di"].items())}
    for k in ("controllers", "hosted_services", "handlers", "contexts", "legacy_data_access", "queue_payloads"):
        data[k] = sorted(data[k], key=lambda x: (x.get("file", ""), x.get("name", x.get("handler", ""))))
    data["routing"] = sorted({json.dumps(r, sort_keys=True) for r in data["routing"]})
    data["routing"] = [json.loads(r) for r in data["routing"]]
    data["routing"].sort(key=lambda r: (r["file"], r["switch_on"], r["code"]))
    data["unsafe_sql"].sort()
    data["endpoint_constants"].sort()
    data["compile_removed"].sort()
    data["empty_projects"].sort()
    data["commented_out_files"].sort()
    data["projects"].sort(key=lambda p: p["name"])
    return data


